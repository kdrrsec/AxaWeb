import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function readEnv(...keys) {
  for (const key of keys) {
    const value = process.env[key];
    if (typeof value === "string" && value.trim()) return value.trim();
  }
  return "";
}

/**
 * Schrijft publieke env naar js/config/public-env.js (build-time).
 * Ondersteunt NEXT_PUBLIC_* (Vercel-conventie) en PUBLIC_* aliassen.
 */
export function injectPublicEnv() {
  const env = {
    GA_MEASUREMENT_ID: readEnv("NEXT_PUBLIC_GA_MEASUREMENT_ID", "PUBLIC_GA_MEASUREMENT_ID"),
    CLARITY_PROJECT_ID: readEnv("NEXT_PUBLIC_CLARITY_PROJECT_ID", "PUBLIC_CLARITY_PROJECT_ID"),
    GOOGLE_SITE_VERIFICATION: readEnv(
      "GOOGLE_SITE_VERIFICATION",
      "NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION"
    ),
  };

  const file = `/**
 * Auto-generated by scripts/inject-public-env.js — do not edit by hand.
 * Empty strings keep analytics/verification disabled safely.
 */
export const publicEnv = Object.freeze({
  GA_MEASUREMENT_ID: ${JSON.stringify(env.GA_MEASUREMENT_ID)},
  CLARITY_PROJECT_ID: ${JSON.stringify(env.CLARITY_PROJECT_ID)},
  GOOGLE_SITE_VERIFICATION: ${JSON.stringify(env.GOOGLE_SITE_VERIFICATION)},
});
`;

  writeFileSync(join(root, "js/config/public-env.js"), file, "utf8");
  return env;
}
